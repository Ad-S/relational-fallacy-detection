"""All tables and figures for the final paper, computed from the session result files.

Inputs: finetune/session_results/<run>/predictions.csv (fine-tuning), .../xgb_grouped/predictions.csv,
.../probing/probe_results.csv, data/annotations/dataset_augmented_all_v2.csv.
All models share the same grouped folds (verified in xgb_grouped.py), so comparisons are paired.
Confidence intervals: cluster bootstrap over conversation groups (an example and its variants form one
cluster), 2,000 resamples, on per-example correctness averaged over seeds 0-2.

Usage: python3 src/analysis/final_results.py
Writes: results_final/*.csv, results_final/RESULTS.md, results_final/fig_*.{pdf,png}
"""
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "finetune" / "session_results"
OUT = ROOT / "results_final"
OUT.mkdir(exist_ok=True)
sys.path.insert(0, str(ROOT / "finetune"))
from triggers import mask_triggers  # noqa: E402

SHAPES = {"motte_bailey": "Motte-and-bailey", "strawman": "Strawman"}
FT = {"nli_pair": "DeBERTa-NLI (A,C,B)", "plain_pair": "DeBERTa plain (A,C,B)", "nli_bonly": "DeBERTa-NLI (B only)",
      "nli_pair_lr1e-5": "DeBERTa-NLI lr 1e-5", "nli_pair_lr3e-5": "DeBERTa-NLI lr 3e-5",
      "nli_pair_frac0.25": "train 25%", "nli_pair_frac0.5": "train 50%", "nli_pair_frac0.75": "train 75%"}
XGB = {"xgb_NLI + Specificity": "XGBoost NLI+spec", "xgb_NLI only": "XGBoost NLI", "xgb_Specificity only": "XGBoost spec"}
BLUE, ORANGE, AQUA, GRAY, INK2 = "#2a78d6", "#eb6834", "#1baf7a", "#a9a8a1", "#52514e"
plt.rcParams.update({"font.size": 8, "axes.spines.top": False, "axes.spines.right": False, "axes.titlesize": 9,
                     "legend.fontsize": 7, "figure.dpi": 150, "savefig.bbox": "tight"})

data = pd.read_csv(ROOT / "data" / "annotations" / "dataset_augmented_all_v2.csv", keep_default_na=False)
group = dict(zip(data.pair_id, data.conversation_id))


def load():
    frames = []
    for run in FT:
        p = pd.read_csv(RES / run / "predictions.csv", keep_default_na=False)
        frames.append(p.assign(config=run))
    x = pd.read_csv(RES / "xgb_grouped" / "predictions.csv", keep_default_na=False)
    frames.append(x)
    p = pd.concat(frames, ignore_index=True)
    p["group"] = p.pair_id.map(group)
    p["src"] = p.pair_id.map(dict(zip(data.pair_id, data.source)))
    return p


def per_seed(g):
    y, pr, prob = g.y.values, g.pred.values, g.prob.values
    tp, fp, fn = ((y == 1) & (pr == 1)).sum(), ((y == 0) & (pr == 1)).sum(), ((y == 1) & (pr == 0)).sum()
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    return pd.Series(dict(accuracy=(y == pr).mean(), f1=2 * prec * rec / (prec + rec) if prec + rec else 0.0,
                          auc=roc_auc_score(y, prob), precision=prec, recall=rec))


def summarize(p, configs):
    rows = []
    for cfg in configs:
        for shape in SHAPES:
            g = p[(p.config == cfg) & (p["shape"] == shape)]
            s = g.groupby("seed").apply(per_seed, include_groups=False)
            rows.append(dict(config=cfg, shape=shape, n=g.pair_id.nunique(), seeds=len(s),
                             **{f"{m}_mean": s[m].mean() for m in s}, **{f"{m}_std": s[m].std(ddof=0) for m in s}))
    return pd.DataFrame(rows)


def cluster_boot_diff(p, a, b, shape, seeds=(0, 1, 2), n=2000, seed=0):
    def correct(cfg):
        g = p[(p.config == cfg) & (p["shape"] == shape) & (p.seed.isin(seeds))]
        return g.assign(c=(g.y == g.pred).astype(float)).groupby("pair_id").c.mean()
    ca, cb = correct(a), correct(b)
    ids = ca.index.intersection(cb.index)
    d = (ca[ids] - cb[ids])
    grp = pd.Series([group[i] for i in ids], index=ids)
    clusters = grp.unique()
    by = {c: d[grp == c].values for c in clusters}
    rng = np.random.default_rng(seed)
    boots = []
    for _ in range(n):
        pick = rng.choice(clusters, len(clusters), replace=True)
        v = np.concatenate([by[c] for c in pick])
        boots.append(v.mean())
    lo, hi = np.percentile(boots, [2.5, 97.5])
    return d.mean(), lo, hi, len(ids), len(clusters)


def fmt(m, s):
    return f"{m:.3f} ± {s:.3f}"


def main():
    p = load()
    lines = ["# Final results (generated by src/analysis/final_results.py)", ""]
    maj = []
    for shape, name in SHAPES.items():
        g = data[data.type_candidate == shape]
        pos = (g.label != "NONE").mean()
        maj.append(dict(config="majority", shape=shape, n=len(g), accuracy_mean=max(pos, 1 - pos), f1_mean=0.0 if pos < .5 else 2 * pos / (1 + pos), auc_mean=0.5))
    maj = pd.DataFrame(maj)

    # ---- Table 1: main comparison ----
    main_cfg = ["xgb_Specificity only", "xgb_NLI only", "xgb_NLI + Specificity", "plain_pair", "nli_pair", "nli_bonly"]
    t1 = summarize(p, main_cfg)
    t1.to_csv(OUT / "table1_main.csv", index=False)
    lines += ["## Table 1 - main comparison (mean ± sd over seeds; same grouped 5-fold CV)", "",
              "| Model | Shape | n | seeds | Accuracy | F1 | AUC |", "|---|---|---|---|---|---|---|"]
    for _, r in maj.iterrows():
        lines.append(f"| Majority class | {SHAPES[r['shape']]} | {r.n} | - | {r.accuracy_mean:.3f} | {r.f1_mean:.3f} | 0.500 |")
    for _, r in t1.iterrows():
        nm = XGB.get(r.config, FT.get(r.config))
        lines.append(f"| {nm} | {SHAPES[r['shape']]} | {r.n} | {r.seeds} | {fmt(r.accuracy_mean, r.accuracy_std)} | "
                     f"{fmt(r.f1_mean, r.f1_std)} | {fmt(r.auc_mean, r.auc_std)} |")

    # ---- paired differences ----
    lines += ["", "## Paired accuracy differences (cluster bootstrap 95% CI, seeds 0-2)", "",
              "| Comparison | Shape | Δ accuracy | 95% CI | n examples | n clusters |", "|---|---|---|---|---|---|"]
    diffs = []
    for a, b, label in [("nli_pair", "xgb_NLI + Specificity", "Fine-tuned NLI vs XGBoost NLI+spec"),
                        ("nli_pair", "plain_pair", "NLI init vs plain init"),
                        ("nli_pair", "nli_bonly", "Pair input (A,C,B) vs B only")]:
        for shape in SHAPES:
            m, lo, hi, n, k = cluster_boot_diff(p, a, b, shape)
            diffs.append(dict(comparison=label, shape=shape, diff=m, ci_low=lo, ci_high=hi, n=n, clusters=k))
            lines.append(f"| {label} | {SHAPES[shape]} | {m:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {n} | {k} |")
    pd.DataFrame(diffs).to_csv(OUT / "table2_paired_differences.csv", index=False)

    # ---- trigger masking ----
    lines += ["", "## Trigger masking (claim B with the selection trigger phrases deleted, at test time)", "",
              "| Model | Shape | rows changed by masking | Acc unmasked (changed rows) | Acc masked (changed rows) | F1 unmasked (all) | F1 masked (all) |",
              "|---|---|---|---|---|---|---|"]
    changed = {r.pair_id for r in data.itertuples() if mask_triggers(r.claim_B, r.type_candidate) != " ".join(r.claim_B.split())}
    mask_rows = []
    for cfg in ["nli_pair", "plain_pair", "nli_bonly"]:
        for shape in SHAPES:
            g = p[(p.config == cfg) & (p["shape"] == shape)]
            ch = g[g.pair_id.isin(changed)]
            acc_u = ch.groupby("seed").apply(lambda h: (h.y == h.pred).mean(), include_groups=False).mean()
            acc_m = ch.groupby("seed").apply(lambda h: (h.y == h.pred_masked).mean(), include_groups=False).mean()
            f1u = g.groupby("seed").apply(per_seed, include_groups=False).f1.mean()
            f1m = g.assign(pred=g.pred_masked).groupby("seed").apply(per_seed, include_groups=False).f1.mean()
            nch = ch.pair_id.nunique()
            mask_rows.append(dict(config=cfg, shape=shape, changed_rows=nch, acc_unmasked_changed=acc_u,
                                  acc_masked_changed=acc_m, f1_unmasked=f1u, f1_masked=f1m))
            lines.append(f"| {FT[cfg]} | {SHAPES[shape]} | {nch} | {acc_u:.3f} | {acc_m:.3f} | {f1u:.3f} | {f1m:.3f} |")
    pd.DataFrame(mask_rows).to_csv(OUT / "table3_masking.csv", index=False)

    # ---- by source ----
    lines += ["", "## Accuracy by data source (both shapes pooled, mean over seeds)", "",
              "| Model | real CMV | hand-written | variants |", "|---|---|---|---|"]
    src_rows = []
    srcmap = {"reddit_cmv": "real CMV", "handwritten": "hand-written", "handwritten_variant": "variants", "real_variant": "variants"}
    for cfg in ["xgb_NLI + Specificity", "nli_pair", "nli_bonly"]:
        g = p[p.config == cfg].assign(S=lambda d: d.src.map(srcmap))
        acc = g.groupby(["S", "seed"]).apply(lambda h: (h.y == h.pred).mean(), include_groups=False).groupby("S").mean()
        n = g.groupby("S").pair_id.nunique()
        src_rows.append(dict(config=cfg, **{f"acc_{k}": acc[k] for k in acc.index}, **{f"n_{k}": n[k] for k in n.index}))
        lines.append(f"| {XGB.get(cfg, FT.get(cfg))} | {acc['real CMV']:.3f} (n={n['real CMV']}) | "
                     f"{acc['hand-written']:.3f} (n={n['hand-written']}) | {acc['variants']:.3f} (n={n['variants']}) |")
    pd.DataFrame(src_rows).to_csv(OUT / "table4_by_source.csv", index=False)

    # ---- LR sensitivity and learning curve (seeds 0-2) ----
    p3 = p[p.seed.isin([0, 1, 2])]
    lr = summarize(p3, ["nli_pair_lr1e-5", "nli_pair", "nli_pair_lr3e-5"]).assign(
        lr=lambda d: d.config.map({"nli_pair_lr1e-5": 1e-5, "nli_pair": 1.5e-5, "nli_pair_lr3e-5": 3e-5}))
    lr.to_csv(OUT / "table5_lr_sensitivity.csv", index=False)
    lc = summarize(p3, ["nli_pair_frac0.25", "nli_pair_frac0.5", "nli_pair_frac0.75", "nli_pair"]).assign(
        frac=lambda d: d.config.map({"nli_pair_frac0.25": .25, "nli_pair_frac0.5": .5, "nli_pair_frac0.75": .75, "nli_pair": 1.0}))
    lc.to_csv(OUT / "table6_learning_curve.csv", index=False)
    lines += ["", "## Learning-rate sensitivity (DeBERTa-NLI, seeds 0-2)", "", "| lr | Shape | Accuracy | F1 | AUC |", "|---|---|---|---|---|"]
    for _, r in lr.sort_values(["shape", "lr"]).iterrows():
        lines.append(f"| {r.lr:g} | {SHAPES[r['shape']]} | {fmt(r.accuracy_mean, r.accuracy_std)} | {fmt(r.f1_mean, r.f1_std)} | {fmt(r.auc_mean, r.auc_std)} |")
    lines += ["", "## Learning curve (fraction of training conversations kept; seeds 0-2)", "", "| fraction | Shape | Accuracy | F1 | AUC |", "|---|---|---|---|---|"]
    for _, r in lc.sort_values(["shape", "frac"]).iterrows():
        lines.append(f"| {r.frac:g} | {SHAPES[r['shape']]} | {fmt(r.accuracy_mean, r.accuracy_std)} | {fmt(r.f1_mean, r.f1_std)} | {fmt(r.auc_mean, r.auc_std)} |")

    # ---- counterfactual flip pairs ----
    flips = data[data.kind == "flip"][["pair_id", "source_pair_id", "type_candidate"]]
    lines += ["", "## Counterfactual flip pairs (hand-written example vs its label-flipped edit; generated labels)", "",
              "| Model | pairs | both correct | prediction changes between the two | ", "|---|---|---|---|"]
    flip_rows = []
    for cfg in ["xgb_NLI + Specificity", "nli_pair", "nli_bonly"]:
        g = p[p.config == cfg].set_index(["seed", "pair_id"])
        both, change, tot = 0, 0, 0
        for seed in sorted(p[p.config == cfg].seed.unique()):
            for f in flips.itertuples():
                if (seed, f.pair_id) not in g.index or (seed, f.source_pair_id) not in g.index:
                    continue
                a, b = g.loc[(seed, f.source_pair_id)], g.loc[(seed, f.pair_id)]
                tot += 1
                both += int(a.pred == a.y and b.pred == b.y)
                change += int(a.pred != b.pred)
        flip_rows.append(dict(config=cfg, pair_evaluations=tot, both_correct=both / tot, prediction_changes=change / tot))
        lines.append(f"| {XGB.get(cfg, FT.get(cfg))} | {len(flips)} (x seeds = {tot}) | {both / tot:.2f} | {change / tot:.2f} |")
    pd.DataFrame(flip_rows).to_csv(OUT / "table7_flip_pairs.csv", index=False)

    # ---- probing ----
    pr = pd.read_csv(RES / "probing" / "probe_results.csv")
    best = pr[pr.metric == "auc"].sort_values("mean").groupby(["model", "shape"]).tail(1)
    lines += ["", "## Layer probing (frozen encoders, logistic regression per layer; best AUC)", "",
              "| Encoder | Shape | best layer | AUC | layer-0 AUC | last-layer AUC |", "|---|---|---|---|---|---|"]
    for _, r in best.sort_values(["shape", "model"]).iterrows():
        sub = pr[(pr.model == r.model) & (pr["shape"] == r["shape"]) & (pr.metric == "auc")].set_index("layer")["mean"]
        lines.append(f"| {r.model} | {SHAPES[r['shape']]} | {int(r.layer)} | {r['mean']:.3f} | {sub.iloc[0]:.3f} | {sub.iloc[-1]:.3f} |")

    (OUT / "RESULTS.md").write_text("\n".join(lines) + "\n")
    figures(p, t1, maj, pr, lc)
    print("\n".join(lines))


def figures(p, t1, maj, pr, lc):
    # Fig 1: main comparison, F1 and AUC per shape
    order = [("xgb_Specificity only", GRAY), ("xgb_NLI + Specificity", AQUA), ("nli_bonly", ORANGE),
             ("plain_pair", "#86b6ef"), ("nli_pair", BLUE)]
    fig, axes = plt.subplots(1, 2, figsize=(6.3, 2.3), sharey=True)
    for ax, metric, title in zip(axes, ["f1", "auc"], ["F1 (positive class)", "ROC-AUC"]):
        for si, shape in enumerate(SHAPES):
            for mi, (cfg, col) in enumerate(order):
                r = t1[(t1.config == cfg) & (t1["shape"] == shape)].iloc[0]
                x = si + (mi - 2) * 0.16
                ax.bar(x, r[f"{metric}_mean"], 0.14, color=col, label=XGB.get(cfg, FT.get(cfg)) if si == 0 else None)
                ax.errorbar(x, r[f"{metric}_mean"], yerr=r[f"{metric}_std"], color="k", lw=0.8, capsize=1.5)
        if metric == "auc":
            ax.axhline(0.5, color=INK2, ls=":", lw=0.8)
        ax.set_xticks(range(len(SHAPES)))
        ax.set_xticklabels(list(SHAPES.values()))
        ax.set_title(title)
        ax.set_ylim(0, 1)
    axes[0].legend(loc="upper center", bbox_to_anchor=(1.05, -0.12), ncol=5, frameon=False)
    fig.savefig(OUT / "fig_main_comparison.pdf")
    fig.savefig(OUT / "fig_main_comparison.png", dpi=200)
    plt.close(fig)

    # Fig 2: probing AUC by layer
    fig, axes = plt.subplots(1, 2, figsize=(6.3, 2.0), sharey=True)
    for ax, shape in zip(axes, SHAPES):
        for model, col, lab in [("deberta_nli", BLUE, "DeBERTa-NLI (frozen)"), ("deberta_plain", GRAY, "DeBERTa plain (frozen)")]:
            s = pr[(pr.model == model) & (pr["shape"] == shape) & (pr.metric == "auc")].sort_values("layer")
            ax.plot(s.layer, s["mean"], color=col, lw=1.4, label=lab)
            ax.fill_between(s.layer, s["mean"] - s["std"], s["mean"] + s["std"], color=col, alpha=0.2, lw=0)
        ft = t1[(t1.config == "nli_pair") & (t1["shape"] == shape)].auc_mean.iloc[0]
        ax.axhline(ft, color=BLUE, ls="--", lw=0.9, label="fine-tuned DeBERTa-NLI")
        ax.axhline(0.5, color=INK2, ls=":", lw=0.8)
        ax.set_title(SHAPES[shape])
        ax.set_xlabel("layer")
    axes[0].set_ylabel("probe ROC-AUC")
    axes[0].legend(loc="lower right", frameon=False)
    fig.savefig(OUT / "fig_probing.pdf")
    fig.savefig(OUT / "fig_probing.png", dpi=200)
    plt.close(fig)

    # Fig 3: learning curve (ROC-AUC)
    fig, axes = plt.subplots(1, 2, figsize=(6.3, 1.9), sharey=True)
    for ax, shape in zip(axes, SHAPES):
        s = lc[lc["shape"] == shape].sort_values("frac")
        ax.errorbar(s.frac * 100, s.auc_mean, yerr=s.auc_std, color=BLUE, marker="o", ms=3, lw=1.2, capsize=2,
                    label="fine-tuned DeBERTa-NLI")
        xg = t1[(t1.config == "xgb_NLI + Specificity") & (t1["shape"] == shape)].auc_mean.iloc[0]
        ax.axhline(xg, color=AQUA, ls="--", lw=0.9, label="XGBoost NLI+spec (100% of data)")
        ax.axhline(0.5, color=INK2, ls=":", lw=0.8)
        ax.set_title(SHAPES[shape])
        ax.set_xlabel("% of training conversations")
        ax.set_xticks([25, 50, 75, 100])
    axes[0].set_ylabel("ROC-AUC")
    axes[1].legend(loc="lower right", frameon=False)
    fig.savefig(OUT / "fig_learning_curve.pdf")
    fig.savefig(OUT / "fig_learning_curve.png", dpi=200)
    plt.close(fig)


if __name__ == "__main__":
    main()
